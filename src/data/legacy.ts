// Разминка v1: №1–2 — 50%×12 и 75%×6, остальные — 50%×12, свой вес — 1×5, планка — нет.
function warmupFor(index: number, mode: Mode): Warmup[] {
  if (mode === 'time') return [];
  if (mode === 'bodyweight') return [{ pct: 0, reps: 5 }];
  return index < 2
    ? [
        { pct: 0.5, reps: 12 },
        { pct: 0.75, reps: 6 },
      ]
    : [{ pct: 0.5, reps: 12 }];
}

